#!/usr/bin/env python3
"""Tables for the mask controller (skypluto_maskctl.v) and its bit-exact model (sim/maskctl_model.py).

Writes
  hdl/library/skypluto_wfm/skypluto_maskctl_tabs.vh   gain steps, Hann window, FFT twiddles, halfband midpoint taps (case ROMs)
  hdl/library/skypluto_wfm/data/maskctl_sin.mem       sine table, 4096 x 14 bit (round(8191 sin(2 pi p / 4096)), two's complement)
The values are defined in sim/maskctl_model.py; this script only formats them.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'sim'))
import maskctl_model as M

LIB = os.path.join(ROOT, 'hdl', 'library', 'skypluto_wfm')

def case_fn(name, width, idx_w, values, signed=False):
    s = ['    function %s[%d:0] %s(input [%d:0] i);' % ('signed ' if signed else '', width - 1, name, idx_w - 1),
         '        case (i)']
    for i, v in enumerate(values):
        lit = ('-' if v < 0 else '') + "%d'sd%d" % (width, abs(v)) if signed else "%d'd%d" % (width, v)
        s.append('            %d: %s = %s;' % (i, name, lit))
    s += ["            default: %s = 0;" % name, '        endcase', '    endfunction']
    return '\n'.join(s)

out = ['// Generated by scripts/gen_maskctl.py from sim/maskctl_model.py - do not edit.',
       '// Gain steps (Q16, %.3f dB apart), Hann window (Q15), FFT64 twiddles (Q15), halfband midpoint taps (Q15).' % M.QSTEP_DB,
       case_fn('mc_gain', 17, 5, [int(v) for v in M.GTAB]),
       case_fn('mc_win', 16, 6, [int(v) for v in M.WIN]),
       case_fn('mc_twr', 17, 5, [int(v) for v in M.TW_R], signed=True),
       case_fn('mc_twi', 17, 5, [int(v) for v in M.TW_I], signed=True),
       case_fn('mc_hb', 17, 3, [int(v) for v in M.HB], signed=True), '']
with open(os.path.join(LIB, 'skypluto_maskctl_tabs.vh'), 'w', newline='\n') as f:
    f.write('\n'.join(out))
with open(os.path.join(LIB, 'data', 'maskctl_sin.mem'), 'w', newline='\n') as f:
    for v in M.SIN:
        f.write('%04x\n' % (int(v) & 0x3FFF))
print('written: skypluto_maskctl_tabs.vh, data/maskctl_sin.mem')
