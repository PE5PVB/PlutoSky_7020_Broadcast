"""Writes skypluto_dab_interp_coefs.vh: the coefficients of the 3/2 interpolator of dab_ofdm_model.py as a Verilog function."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dab_ofdm_model as M

h = [int(v) for v in M.HI]
assert max(abs(v) for v in h) < (1 << 17)
o = ['// SPDX-License-Identifier: Apache-2.0', '// GENERATED by gen_interp.py from dab_ofdm_model.py - do not edit.',
     '// 3/2 interpolator, %d taps at 6.144 MS/s, 18 bit, scale 2^17 x 3 (zero stuffing)' % len(h),
     'function signed [17:0] c_int(input integer k);', '    case (k)']
o += ['        %d: c_int = %d;' % (k, v) for k, v in enumerate(h)]
o += ['        default: c_int = 0;', '    endcase', 'endfunction']
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'skypluto_dab_interp_coefs.vh')
open(p, 'w', newline='\n').write('\n'.join(o) + '\n')
print('written', p, 'sum', sum(h))
# twiddle ROM e^{+j 2 pi m / 2048}, m = 0..1023, scale 2^16, packed {re[17:0], im[17:0]}
o = ['// SPDX-License-Identifier: Apache-2.0', '// GENERATED by gen_interp.py from dab_ofdm_model.py - do not edit.',
     '// IFFT twiddles e^{+j 2 pi m / 2048}, m = 0..1023, round(2^16 (cos, sin)), packed {re[17:0], im[17:0]}',
     'function [35:0] c_tw(input [9:0] m);', '    case (m)']
for m in range(1024):
    r, i = int(M.TW[m, 0]), int(M.TW[m, 1])
    o.append("        10'd%d: c_tw = {18'h%05x, 18'h%05x};" % (m, r & 0x3FFFF, i & 0x3FFFF))
o += ["        default: c_tw = 36'd0;", '    endcase', 'endfunction']
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'skypluto_dab_twiddle.vh')
open(p, 'w', newline='\n').write('\n'.join(o) + '\n')
print('written', p)
