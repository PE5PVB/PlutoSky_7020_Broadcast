// =============================================================================
// skypluto_maskctl - mask controller: per block of 64 composite samples, the largest gain at which the FM signal stays
// inside the ITU-R SM.1268 mask (minus a margin)
// -----------------------------------------------------------------------------
// Runs on the AXI clock (100 MHz, ~520 clocks per 192 kHz sample). The conditioner (skypluto_sigcond) sends every composite
// sample (after its fade) with its number {block[7:0], position[5:0]}; it delays its own limiter path by 256 samples, so the
// gain for a block arrives in time. Per block b (samples 64b .. 64b+63) and a trial gain g:
//   x2      the composite at 384 kHz: the samples, and between x[n] and x[n+1] a 16-tap halfband midpoint
//   frames  8 frames of 64 samples (384 kHz) starting at 128b + 16i: they cover the block and the first 24 samples of the next
//   FM      per frame from phase 0: inc = ((x2 * g) >> 16) * kdev (32-bit phase: 750 Hz per step / 384 kHz = 2^-9 exactly),
//           sin/cos from the top 12 phase bits (14-bit table), Hann window, 64-point FFT (radix 2, Q15 twiddles, floor)
//   test    on the 32 skirt bins (6 kHz each, |k| = 13..28 = 78..168 kHz): (re^2 + im^2) >> 10 <= thr[|k| - 13]
// The thresholds come from the mask and the margin (computed by the ARM, see skypluto-ctl). Search: gain step 0 (1.0) if it
// passes, otherwise a binary search over steps 1..31 (0.375 dB apart, down to -11.6 dB) for the first step that passes.
// The result {block, step} goes back to the conditioner, which applies the step to the block (and to the first 24 samples of
// the next block, which these frames also covered) as an extra g_req of its look-ahead limiter.
// Worst case per block: 6 evaluations x 8 frames x ~330 clocks = ~16000 clocks of the ~33000 available.
// Bit-exact model: sim/maskctl_model.py (tables generated by scripts/gen_maskctl.py).
// =============================================================================
`timescale 1ns/1ps

module skypluto_maskctl (
    input  wire               clk,
    input  wire               rst,
    // sample stream from the conditioner (FWFT FIFO): {block[7:0], position[5:0], x[23:0]}
    input  wire [37:0]        s_data,
    input  wire               s_empty,
    output reg                s_rd,
    // results to the conditioner: {block[7:0], step[4:0]}
    output reg  [12:0]        r_data,
    output reg                r_wr,
    input  wire               r_full,
    // control
    input  wire               en,            // 0: every block gets step 0 (no limiting) without an evaluation
    input  wire [7:0]         kdev,          // the modulator's deviation scale (750 Hz per step at full scale)
    input  wire               thr_we,
    input  wire [3:0]         thr_idx,
    input  wire [27:0]        thr_val,
    input  wire               clr,           // clear the statistics
    // status
    output reg  [31:0]        lim_blocks,    // blocks with a step > 0
    output reg  [4:0]         max_q,         // largest step since clr
    output reg  [4:0]         last_q,
    output reg  [15:0]        overruns,      // blocks whose samples were overwritten before their turn (step 31 sent)
    output reg  [15:0]        resyncs        // breaks in the sample numbering (a reset of the conditioner)
);
    `include "skypluto_maskctl_tabs.vh"

    // ---- sample and midpoint rings (index = sample number mod 256), thresholds -----------------------------------------
    reg signed [23:0] xr [0:255];
    reg signed [24:0] mr [0:255];            // mr[n] = midpoint between x[n] and x[n+1] (25 bits: the halfband overshoots full scale)
    reg [27:0] thr [0:15];
    integer ii;
    initial for (ii = 0; ii < 256; ii = ii + 1) begin xr[ii] = 0; mr[ii] = 0; end
    initial for (ii = 0; ii < 16; ii = ii + 1) thr[ii] = 28'hFFFFFFF;
    always @(posedge clk) if (thr_we) thr[thr_idx] <= thr_val;

    // ---- intake: store a sample, then compute the midpoint between x[newest-8] and x[newest-7] (8 MACs) -----------------
    reg        in_wait;                      // one clock after a pop the next word is on s_data
    reg        synced;
    reg [13:0] rcv;                          // number of the newest stored sample (mod 16384)
    reg        mac_busy;
    reg [3:0]  mk;
    reg [13:0] mn;
    reg signed [42:0] macc;
    reg signed [24:0] mpair;
    reg signed [16:0] mcoef;
    reg        mpv;
    reg        rs_pulse;                     // to the engine: restart at block start rs_b14
    reg [13:0] rs_b14;
    wire [13:0] tag = s_data[37:24];

    always @(posedge clk) begin
        if (rst) begin
            s_rd <= 1'b0; in_wait <= 1'b0; synced <= 1'b0; rcv <= 0; mac_busy <= 1'b0; mk <= 0; mn <= 0;
            macc <= 0; mpair <= 0; mcoef <= 0; mpv <= 1'b0; resyncs <= 0; rs_pulse <= 1'b0; rs_b14 <= 0;
        end else begin
            s_rd <= 1'b0; rs_pulse <= 1'b0;
            if (clr) resyncs <= 0;
            if (in_wait) in_wait <= 1'b0;
            else if (!s_empty && !mac_busy) begin
                s_rd <= 1'b1; in_wait <= 1'b1;
                xr[tag[7:0]] <= s_data[23:0];
                rcv <= tag;
                if (!synced || tag != rcv + 1'b1) begin      // first sample or a break: restart at the next block start
                    synced <= 1'b1;
                    if (synced) resyncs <= resyncs + 1'b1;
                    rs_b14 <= (tag[5:0] == 6'd0) ? tag : {tag[13:6] + 1'b1, 6'd0};
                    rs_pulse <= 1'b1;
                end
                mn <= tag - 14'd8; mk <= 0; mac_busy <= 1'b1; macc <= 0; mpv <= 1'b0;
            end
            // midpoint: sum over k of hb[k] * (x[mn-k] + x[mn+1+k]), then >> 15 (mk 0..7 load, 1..8 accumulate, 10 store)
            if (mac_busy) begin
                mk <= mk + 1'b1;
                mpv <= (mk < 4'd8);
                if (mk < 4'd8) begin
                    mpair <= xr[mn[7:0] - mk] + xr[mn[7:0] + 8'd1 + mk];
                    mcoef <= mc_hb(mk[2:0]);
                end
                if (mpv) macc <= macc + mpair * mcoef;
                if (mk == 4'd10) begin mr[mn[7:0]] <= macc >>> 15; mac_busy <= 1'b0; end
            end
        end
    end

    // ---- evaluation engine -------------------------------------------------------------------------------------------
    localparam [2:0] E_IDLE = 0, E_EVAL = 1, E_GEN = 2, E_FFT = 3, E_POW = 4, E_FRDONE = 5, E_EVDONE = 6, E_OUT = 7;
    reg [2:0]  est;
    reg [13:0] ev_b14;                       // first sample of the block under evaluation (64 x block)
    reg        have_b;
    reg [4:0]  q_try, lo, hi, res_q;
    reg        bin_phase;                    // 0 = trying step 0, 1 = binary search over 1..31
    reg        fail;
    reg [2:0]  fr;
    reg [6:0]  t;                            // issue counter (samples, butterflies, bins)
    reg [2:0]  stg;                          // FFT stage 0..5
    reg [16:0] g;

    // FFT buffers: the generation writes A; stage 0 reads A and writes B, stage 1 B -> A, ..., stage 5 B -> A: result in A
    reg signed [23:0] ar [0:63], ai [0:63], br [0:63], bi [0:63];

    // generation pipeline
    wire [14:0] i384 = {ev_b14, 1'b0} + {fr, 4'd0} + {9'd0, t[5:0]};   // 384 kHz index (mod 2^15)
    reg  signed [24:0] g_smp;  reg g_v1; reg [5:0] g_t1;
    reg  signed [41:0] g_prod; reg g_v2; reg [5:0] g_t2;
    reg  signed [34:0] g_inc;  reg g_v3; reg [5:0] g_t3;
    reg  [31:0] phi;
    reg  [11:0] g_ph;          reg g_v4; reg [5:0] g_t4;
    reg                           g_v5; reg [5:0] g_t5;
    reg  signed [29:0] g_wr, g_wi; reg g_v6; reg [5:0] g_t6;
    wire signed [13:0] s_sin, s_cos;
    skypluto_sincos #(.ADDR_W(12), .DATA_W(14), .LUT_FILE("maskctl_sin.mem")) u_sc (
        .clk(clk), .phase(g_ph), .sin_out(s_sin), .cos_out(s_cos));
    function [5:0] brev(input [5:0] v); brev = {v[0], v[1], v[2], v[3], v[4], v[5]}; endfunction

    // butterfly pipeline: issue (0) -> read (1) -> products (2) -> twiddled bottom (3) -> write (4)
    wire [5:0] jj    = {1'b0, t[4:0]};
    wire [5:0] hspan = 6'd1 << stg;
    wire [5:0] k_in  = jj & (hspan - 6'd1);
    wire [5:0] top   = ((jj >> stg) << (stg + 3'd1)) | k_in;
    wire [4:0] twix  = k_in[4:0] << (3'd5 - stg);
    reg        b_v0, b_v1, b_v2, b_v3;
    reg        b_d0, b_d1, b_d2, b_d3;       // 0: read A, write B; 1: read B, write A
    reg [5:0]  b_t0, b_b0, b_t1, b_b1, b_t2, b_b2, b_t3, b_b3;
    reg signed [16:0] b_wr0, b_wi0, b_wr1, b_wi1;
    reg signed [23:0] b_ar, b_ai, b_br, b_bi, b_ar2, b_ai2, b_ar3, b_ai3, b_tr, b_ti;
    reg signed [40:0] b_m1, b_m2, b_m3, b_m4;

    // power pipeline: issue (0) -> read (1) -> power (2) -> compare
    reg  [5:0] p_bin; reg [3:0] p_d0, p_d1, p_d2; reg p_v0, p_v1, p_v2;
    reg  signed [23:0] p_re, p_im;
    reg  [47:0] p_pw;

    wire [13:0] lag   = rcv - ev_b14;                       // samples received beyond the block start
    wire        ready = have_b && !mac_busy && !lag[13] && lag >= 14'd95;
    wire        stale = have_b && !lag[13] && lag >= 14'd200; // the ring (256) could be overwritten during the evaluation

    // next step of the binary search after an evaluation of q_try (lo/hi bound the answer, hi is assumed to pass)
    wire [4:0] n_lo = fail ? q_try + 5'd1 : lo;
    wire [4:0] n_hi = fail ? hi : q_try;
    wire [5:0] n_sum = {1'b0, n_lo} + {1'b0, n_hi};          // 6 bits: lo + hi can reach 62

    always @(posedge clk) begin
        if (rst) begin
            est <= E_IDLE; ev_b14 <= 0; have_b <= 1'b0; q_try <= 0; lo <= 0; hi <= 0; res_q <= 0; bin_phase <= 1'b0;
            fail <= 1'b0; fr <= 0; t <= 0; stg <= 0; g <= 17'd65536; phi <= 0; g_ph <= 0; r_wr <= 1'b0; r_data <= 0;
            g_v1 <= 0; g_v2 <= 0; g_v3 <= 0; g_v4 <= 0; g_v5 <= 0; g_v6 <= 0;
            b_v0 <= 0; b_v1 <= 0; b_v2 <= 0; b_v3 <= 0; p_v0 <= 0; p_v1 <= 0; p_v2 <= 0;
            lim_blocks <= 0; max_q <= 0; last_q <= 0; overruns <= 0;
        end else begin
            r_wr <= 1'b0;
            if (clr) begin lim_blocks <= 0; max_q <= 0; overruns <= 0; end

            // ---------------- generation pipeline ----------------
            g_v1 <= (est == E_GEN) && !t[6]; g_t1 <= t[5:0];
            g_smp <= i384[0] ? mr[i384[8:1]] : xr[i384[8:1]];                       // odd 384 kHz index: the midpoint
            g_v2 <= g_v1; g_t2 <= g_t1; g_prod <= g_smp * $signed({1'b0, g});
            g_v3 <= g_v2; g_t3 <= g_t2; g_inc <= (g_prod >>> 16) * $signed({1'b0, kdev});
            g_v4 <= g_v3; g_t4 <= g_t3;
            if (g_v3) begin g_ph <= phi[31:20]; phi <= phi + g_inc[31:0]; end      // phase = sum of the increments before
            g_v5 <= g_v4; g_t5 <= g_t4;                                               // table read
            g_v6 <= g_v5; g_t6 <= g_t5;
            g_wr <= $signed({1'b0, mc_win(g_t5)}) * s_cos;
            g_wi <= $signed({1'b0, mc_win(g_t5)}) * s_sin;
            if (g_v6) begin ar[brev(g_t6)] <= g_wr >>> 13; ai[brev(g_t6)] <= g_wi >>> 13; end

            // ---------------- butterfly pipeline ----------------
            b_v1 <= b_v0; b_d1 <= b_d0; b_t1 <= b_t0; b_b1 <= b_b0; b_wr1 <= b_wr0; b_wi1 <= b_wi0;
            b_ar <= b_d0 ? br[b_t0] : ar[b_t0]; b_ai <= b_d0 ? bi[b_t0] : ai[b_t0];
            b_br <= b_d0 ? br[b_b0] : ar[b_b0]; b_bi <= b_d0 ? bi[b_b0] : ai[b_b0];
            b_v2 <= b_v1; b_d2 <= b_d1; b_t2 <= b_t1; b_b2 <= b_b1; b_ar2 <= b_ar; b_ai2 <= b_ai;
            b_m1 <= b_wr1 * b_br; b_m2 <= b_wi1 * b_bi; b_m3 <= b_wr1 * b_bi; b_m4 <= b_wi1 * b_br;
            b_v3 <= b_v2; b_d3 <= b_d2; b_t3 <= b_t2; b_b3 <= b_b2; b_ar3 <= b_ar2; b_ai3 <= b_ai2;
            b_tr <= (b_m1 - b_m2) >>> 15; b_ti <= (b_m3 + b_m4) >>> 15;
            if (b_v3) begin
                if (b_d3) begin
                    ar[b_t3] <= b_ar3 + b_tr; ai[b_t3] <= b_ai3 + b_ti; ar[b_b3] <= b_ar3 - b_tr; ai[b_b3] <= b_ai3 - b_ti;
                end else begin
                    br[b_t3] <= b_ar3 + b_tr; bi[b_t3] <= b_ai3 + b_ti; br[b_b3] <= b_ar3 - b_tr; bi[b_b3] <= b_ai3 - b_ti;
                end
            end

            // ---------------- power pipeline ----------------
            p_v1 <= p_v0; p_d1 <= p_d0; p_re <= ar[p_bin]; p_im <= ai[p_bin];
            p_v2 <= p_v1; p_d2 <= p_d1; p_pw <= p_re * p_re + p_im * p_im;
            if (p_v2 && (p_pw[47:10] > {10'd0, thr[p_d2]})) fail <= 1'b1;

            // ---------------- control ----------------
            b_v0 <= 1'b0; p_v0 <= 1'b0;
            case (est)
            E_IDLE: begin
                if (stale) begin                                  // too late for this block: send the safe step
                    res_q <= en ? 5'd31 : 5'd0; overruns <= overruns + 1'b1; est <= E_OUT;
                end else if (ready) begin
                    if (!en) begin res_q <= 5'd0; est <= E_OUT; end
                    else begin q_try <= 5'd0; bin_phase <= 1'b0; est <= E_EVAL; end
                end
            end
            E_EVAL: begin g <= mc_gain(q_try); fr <= 0; fail <= 1'b0; t <= 0; phi <= 0; est <= E_GEN; end
            E_GEN: begin                                          // 64 samples, then wait until the last is in buffer A
                if (!t[6]) t <= t + 1'b1;
                else if (!g_v1 && !g_v2 && !g_v3 && !g_v4 && !g_v5 && !g_v6) begin t <= 0; stg <= 0; est <= E_FFT; end
            end
            E_FFT: begin                                          // 32 butterflies per stage; drain the pipeline between stages
                if (!t[5]) begin
                    b_v0 <= 1'b1; b_d0 <= stg[0]; b_t0 <= top; b_b0 <= top + hspan;
                    b_wr0 <= mc_twr(twix); b_wi0 <= mc_twi(twix);
                    t <= t + 1'b1;
                end else if (!b_v0 && !b_v1 && !b_v2 && !b_v3) begin
                    t <= 0;
                    if (stg == 3'd5) est <= E_POW; else stg <= stg + 3'd1;
                end
            end
            E_POW: begin                                          // the 32 skirt bins: 13..28 and 51..36
                if (!t[5]) begin
                    p_v0 <= 1'b1; p_d0 <= t[3:0];
                    p_bin <= t[4] ? (6'd51 - {2'd0, t[3:0]}) : (6'd13 + {2'd0, t[3:0]});
                    t <= t + 1'b1;
                end else if (!p_v0 && !p_v1 && !p_v2) est <= E_FRDONE;
            end
            E_FRDONE: begin
                if (fail || fr == 3'd7) est <= E_EVDONE;
                else begin fr <= fr + 3'd1; t <= 0; phi <= 0; est <= E_GEN; end
            end
            E_EVDONE: begin
                if (!bin_phase) begin
                    if (!fail) begin res_q <= 5'd0; est <= E_OUT; end
                    else begin bin_phase <= 1'b1; lo <= 5'd1; hi <= 5'd31; q_try <= 5'd16; est <= E_EVAL; end
                end else if (n_lo >= n_hi) begin
                    res_q <= n_lo; est <= E_OUT;
                end else begin
                    lo <= n_lo; hi <= n_hi; q_try <= n_sum[5:1]; est <= E_EVAL;
                end
            end
            E_OUT: begin
                if (!r_full) begin r_wr <= 1'b1; r_data <= {ev_b14[13:6], res_q}; end
                last_q <= res_q;
                if (res_q > max_q) max_q <= res_q;
                if (res_q != 5'd0) lim_blocks <= lim_blocks + 1'b1;
                ev_b14 <= ev_b14 + 14'd64;
                est <= E_IDLE;
            end
            default: est <= E_IDLE;
            endcase

            if (rs_pulse) begin ev_b14 <= rs_b14; have_b <= 1'b1; est <= E_IDLE; end   // a break: restart (wins over the case)
        end
    end
endmodule
