    function signed [17:0] sat18(input signed [47:0] v);
        sat18 = (v > 48'sd131071) ? 18'sd131071 : (v < -48'sd131072) ? -18'sd131072 : v[17:0];
    endfunction
    function signed [15:0] sat16(input signed [47:0] v);
        sat16 = (v > 48'sd32767) ? 16'sd32767 : (v < -48'sd32768) ? -16'sd32768 : v[15:0];
    endfunction

