    // ======== decimator: one 3.072 MS/s sample per 4 clocks into xb; at c16 = 2..9 the 32-tap dot product (16 symmetric pairs, 2 per clock)
    reg signed [15:0] xb [0:63];
    reg [5:0] wp = 6'd0, wps = 6'd0;
    initial for (i = 0; i < 64; i = i + 1) xb[i] = 16'sd0;
    always @(posedge clk) if (c16[1:0] == 2'd0) begin xb[wp] <= x_in; wp <= wp + 6'd1; end

    wire        d_act = (c16 >= 4'd2) && (c16 <= 4'd9);
    wire [3:0]  d_j   = c16 - 4'd2;
    wire [4:0]  d_ka  = {d_j[2:0], 1'b0}, d_kb = {d_j[2:0], 1'b1};
    reg signed [15:0] d_ra1 = 0, d_ra2 = 0, d_rb1 = 0, d_rb2 = 0;
    reg signed [17:0] d_ca = 0, d_cb = 0, d_cap = 0, d_cbp = 0;
    reg signed [16:0] d_pa = 0, d_pb = 0;
    reg signed [34:0] d_ma = 0, d_mb = 0;
    reg signed [39:0] d_acc = 0;
    reg d_vr = 0, d_fr = 0, d_vp = 0, d_fp = 0, d_vm = 0, d_fm = 0;
    always @(posedge clk) begin
        if (c16 == 4'd1) wps <= wp;
        // R: read the pair partners and the coefficients
        d_vr <= d_act; d_fr <= (c16 == 4'd2);
        d_ra1 <= xb[wps - 6'd1 - d_ka]; d_ra2 <= xb[wps - 6'd32 + d_ka];
        d_rb1 <= xb[wps - 6'd1 - d_kb]; d_rb2 <= xb[wps - 6'd32 + d_kb];
        d_ca <= c_dec(d_ka); d_cb <= c_dec(d_kb);
        // P: pre-add
        d_pa <= d_ra1 + d_ra2; d_pb <= d_rb1 + d_rb2; d_cap <= d_ca; d_cbp <= d_cb; d_vp <= d_vr; d_fp <= d_fr;
        // M: multiply
        d_ma <= d_pa * d_cap; d_mb <= d_pb * d_cbp; d_vm <= d_vp; d_fm <= d_fp;
        // A: accumulate (complete at c16 = 13)
        if (d_vm) d_acc <= (d_fm ? 40'sd0 : d_acc) + d_ma + d_mb;
    end

    // ======== channel FIR at 768 kS/s: the decimated sample enters yb at c16 = 13; the 63-tap dot product (31 pairs + centre, 4 per clock)
    // runs at c16 = 15, 0..6 and is complete at c16 = 10
    reg signed [17:0] yb [0:127];
    reg [6:0] yp = 7'd0, yps = 7'd0;
    initial for (i = 0; i < 128; i = i + 1) yb[i] = 18'sd0;
    always @(posedge clk) if (c16 == 4'd13) begin yb[yp] <= sat18(d_acc >>> CB); yp <= yp + 7'd1; end

    wire       c_act = (c16 == 4'd15) || (c16 <= 4'd6);
    wire [2:0] c_j   = c16[2:0] + 3'd1;                 // 15 -> 0, 0 -> 1, ..., 6 -> 7
    reg signed [17:0] c_r1 [0:3], c_r2 [0:3], c_c [0:3], c_cp [0:3];
    reg signed [18:0] c_p [0:3];
    reg signed [36:0] c_m [0:3];
    reg signed [43:0] c_acc = 0;
    reg c_vr = 0, c_fr = 0, c_vp = 0, c_fp = 0, c_vm = 0, c_fm = 0;
    initial for (i = 0; i < 4; i = i + 1) begin c_r1[i] = 0; c_r2[i] = 0; c_c[i] = 0; c_cp[i] = 0; c_p[i] = 0; c_m[i] = 0; end
    always @(posedge clk) begin
        if (c16 == 4'd14) yps <= yp;
        c_vr <= c_act; c_fr <= (c16 == 4'd15);
        for (ci = 0; ci < 4; ci = ci + 1) begin
            c_r1[ci] <= yb[yps - 7'd1 - {2'd0, c_j, 2'd0} - ci[6:0]];
            c_r2[ci] <= ((({c_j, 2'd0} + ci) < 31) ? yb[yps - 7'd63 + {2'd0, c_j, 2'd0} + ci[6:0]] : 18'sd0);   // k = 31 is the centre tap: no partner
            c_c[ci]  <= c_ch(mode, {c_j, 2'd0} + ci);
            c_p[ci]  <= c_r1[ci] + c_r2[ci]; c_cp[ci] <= c_c[ci];
            c_m[ci]  <= c_p[ci] * c_cp[ci];
        end
        c_vp <= c_vr; c_fp <= c_fr; c_vm <= c_vp; c_fm <= c_fp;
        if (c_vm) c_acc <= (c_fm ? 44'sd0 : c_acc) + c_m[0] + c_m[1] + c_m[2] + c_m[3];
    end

    // ======== interpolator: the channel output enters zb at c16 = 10; phase p of the next 4 outputs at c16 = 11, 15, 3, 7: 8 taps each
    reg signed [17:0] zb [0:15];
    reg [3:0] zp = 4'd0, zps = 4'd0;
    initial for (i = 0; i < 16; i = i + 1) zb[i] = 18'sd0;
    always @(posedge clk) if (c16 == 4'd10) begin zb[zp] <= sat18(c_acc >>> CB); zp <= zp + 4'd1; end

    wire       i_act  = (c16 == 4'd11) || (c16 == 4'd15) || (c16 == 4'd3) || (c16 == 4'd7);
    wire [1:0] i_ph   = (c16 == 4'd11) ? 2'd0 : (c16 == 4'd15) ? 2'd1 : (c16 == 4'd3) ? 2'd2 : 2'd3;
    wire [3:0] i_base = (c16 == 4'd11) ? zp : zps;
    reg signed [17:0] i_r [0:7], i_c [0:7];
    reg signed [35:0] i_m [0:7];
    reg signed [38:0] i_s1 [0:3], i_s2 [0:1], i_s3 = 0;
    reg i_vr = 0, i_vm = 0, i_v1 = 0, i_v2 = 0, i_v3 = 0;
    initial for (i = 0; i < 8; i = i + 1) begin i_r[i] = 0; i_c[i] = 0; i_m[i] = 0; end
    initial begin for (i = 0; i < 4; i = i + 1) i_s1[i] = 0; i_s2[0] = 0; i_s2[1] = 0; end
    always @(posedge clk) begin
        if (c16 == 4'd11) zps <= zp;
        i_vr <= i_act;
        for (ii = 0; ii < 8; ii = ii + 1) begin
            i_r[ii] <= zb[i_base - 4'd1 - ii[3:0]];
            i_c[ii] <= c_int({ii[2:0], i_ph});              // tap 4t + p
            i_m[ii] <= i_r[ii] * i_c[ii];
        end
        i_vm <= i_vr;
        for (ii = 0; ii < 4; ii = ii + 1) i_s1[ii] <= i_m[2*ii] + i_m[2*ii+1];
        i_v1 <= i_vm;
        i_s2[0] <= i_s1[0] + i_s1[1]; i_s2[1] <= i_s1[2] + i_s1[3]; i_v2 <= i_v1;
        i_s3 <= i_s2[0] + i_s2[1]; i_v3 <= i_v2;
        if (i_v3) y_out <= sat16(i_s3 >>> CB);              // c16 = 0, 4, 8, 12: held for 4 clocks
    end
endmodule
